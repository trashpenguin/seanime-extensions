const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..')
const sourceIds = JSON.parse(fs.readFileSync(path.join(root, 'collection', 'sources.json'), 'utf8'))
const factories = sourceIds.map(id => {
    const manifest = JSON.parse(fs.readFileSync(path.join(root, id, 'manifest.json'), 'utf8'))
    const source = fs.readFileSync(path.join(root, id, 'provider.js'), 'utf8').replace(/\r\n/g, '\n').trim()
    return `    { id: ${JSON.stringify(id)}, name: ${JSON.stringify(manifest.name)}, create: function(fetch) {\n${source}\nreturn new Provider()\n    } }`
})
const router = fs.readFileSync(path.join(root, 'collection', 'router.js'), 'utf8').replace(/\r\n/g, '\n').trim()
const notices = fs.readFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), 'utf8').replace(/\r\n/g, '\n').trim()
const bundle = [
    '// Generated by npm run build:collection. Edit the individual adapters or collection/router.js.',
    ...notices.split('\n').map(line => line ? '// ' + line : '//'),
    'const COLLECTION_SOURCES = [',
    factories.join(',\n'),
    ']\n',
    router,
    '',
].join('\n')
const output = path.join(root, 'collection', 'provider.js')

if (process.argv.includes('--check')) {
    const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') : ''
    if (current !== bundle) {
        console.error('The collection bundle is out of date. Run npm run build:collection and commit collection/provider.js.')
        process.exitCode = 1
    } else {
        console.log('Collection bundle is up to date.')
    }
} else {
    fs.writeFileSync(output, bundle)
    console.log(`Built collection/provider.js with ${sourceIds.length} manga sources.`)
}
